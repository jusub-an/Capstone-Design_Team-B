def _parse_avatar(avatar):
    import json as _json
    d = {
        "id": avatar.id,
        "user_email": avatar.user_email,
        "gray_mask_url": avatar.gray_mask_url,
        "person_extracted_url": avatar.person_extracted_url,
        "height_cm": avatar.height_cm,
        "measurements": None,
    }
    if avatar.measurements:
        try:
            d["measurements"] = _json.loads(avatar.measurements)
        except Exception:
            d["measurements"] = avatar.measurements
    return d

@app.post("/api/avatar/save", response_model=schemas.AvatarResponse)
async def save_avatar(
    user_email: str = Form(...),
    height_cm: float = Form(...),
    measurements: str = Form(...),
    gray_mask: UploadFile = File(...),
    person_extracted: UploadFile = File(...),
    db: Session = Depends(get_db)
):
    import json as _json

    def _save_file(upload: UploadFile, prefix: str) -> str:
        ext = upload.filename.split(".")[-1] if upload.filename and "." in upload.filename else "jpg"
        fname = f"{prefix}_{uuid.uuid4().hex}.{ext}"
        path = os.path.join(AVATAR_DIR, fname)
        upload.file.seek(0)
        with open(path, "wb") as f:
            shutil.copyfileobj(upload.file, f)
        return f"/uploads/avatars/{fname}"

    gray_url = _save_file(gray_mask, "gray")
    extracted_url = _save_file(person_extracted, "extracted")

    # Store measurements as JSON string (Oracle CLOB / Text column)
    m_str = measurements  # already a JSON string from the client

    existing = db.query(models.Avatar).filter(models.Avatar.user_email == user_email).first()
    if existing:
        for old_url in [existing.gray_mask_url, existing.person_extracted_url]:
            if old_url:
                old_path = os.path.join(AVATAR_DIR, os.path.basename(old_url))
                if os.path.exists(old_path):
                    try:
                        os.remove(old_path)
                    except Exception:
                        pass
        existing.gray_mask_url = gray_url
        existing.person_extracted_url = extracted_url
        existing.measurements = m_str
        existing.height_cm = height_cm
        db.commit()
        db.refresh(existing)
        return _parse_avatar(existing)
    else:
        avatar = models.Avatar(
            user_email=user_email,
            gray_mask_url=gray_url,
            person_extracted_url=extracted_url,
            measurements=m_str,
            height_cm=height_cm
        )
        db.add(avatar)
        db.commit()
        db.refresh(avatar)
        return _parse_avatar(avatar)


