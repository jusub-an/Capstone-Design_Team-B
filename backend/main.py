def auto_migrate_db():
    from sqlalchemy import text
    from database import engine
    if engine is None:
        raise RuntimeError("DB engine not initialized")
    with engine.connect() as conn:
        # Drop legacy table
        try:
            conn.execute(text("DROP TABLE product_sizes"))
            conn.commit()
            print("Dropped old product_sizes table.")
        except Exception:
            pass

        # Add ALL potentially missing columns to products
        for col_ddl in [
            "ALTER TABLE products ADD brand VARCHAR2(100)",
            "ALTER TABLE products ADD description CLOB",
            "ALTER TABLE products ADD owner_email VARCHAR2(100)",
            "ALTER TABLE products ADD avg_rating NUMBER(5,2) DEFAULT 0",
            "ALTER TABLE products ADD review_count INTEGER DEFAULT 0",
            "ALTER TABLE products ADD wish_count INTEGER DEFAULT 0",
            "ALTER TABLE products ADD fitting_image_url VARCHAR2(500)",
        ]:
            try:
                conn.execute(text(col_ddl))
                conn.commit()
                print(f"Migration OK: {col_ddl[:70]}")
            except Exception:
                pass  # column already exists — safe to ignore

        # Create avatars table
        try:
            conn.execute(text("""
                CREATE TABLE avatars (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_email VARCHAR2(100) NOT NULL UNIQUE,
                    gray_mask_url VARCHAR2(500),
                    person_extracted_url VARCHAR2(500),
                    measurements CLOB,
                    height_cm NUMBER(6,2),
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    updated_at TIMESTAMP
                )
            """))
            conn.commit()
            print("Created avatars table.")
        except Exception as e:
            e_str = str(e)
            if "ORA-00955" not in e_str and "already exists" not in e_str.lower():
                print(f"avatars table note: {e_str[:120]}")

        # Create cart_items table
        try:
            conn.execute(text("""
                CREATE TABLE cart_items (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_email VARCHAR2(100) NOT NULL,
                    product_id INTEGER NOT NULL,
                    size_name VARCHAR2(50),
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
            """))
            conn.commit()
            print("Created cart_items table.")
        except Exception as e:
            e_str = str(e)
            if "ORA-00955" not in e_str and "already exists" not in e_str.lower():
                print(f"cart_items table note: {e_str[:120]}")

        print("DB auto-migration completed.")

