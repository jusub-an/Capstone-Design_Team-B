@app.post("/api/measure/clothing")
async def measure_clothing(
    shirt_image: UploadFile = File(...),
    a4_image: UploadFile = File(...),
    shirt_x: float = Form(...),
    shirt_y: float = Form(...),
    shirt_w: float = Form(...),
    shirt_h: float = Form(...),
    a4_x: float = Form(...),
    a4_y: float = Form(...),
    a4_w: float = Form(...),
    a4_h: float = Form(...),
    orig_w: float = Form(...),
    orig_h: float = Form(...),
    category_type: str = Form('Top'),
    shoulder_x1: float = Form(None),
    shoulder_y1: float = Form(None),
    shoulder_x2: float = Form(None),
    shoulder_y2: float = Form(None),
):
    shirt_bytes = await shirt_image.read()
    a4_bytes = await a4_image.read()

    shirt_rect = {'x': shirt_x, 'y': shirt_y, 'w': shirt_w, 'h': shirt_h}
    a4_rect = {'x': a4_x, 'y': a4_y, 'w': a4_w, 'h': a4_h}

    try:
        engine = get_clothing_measure_engine()
        
        shoulder_pts = None
        if shoulder_x1 is not None and shoulder_y1 is not None and shoulder_x2 is not None and shoulder_y2 is not None:
            shoulder_pts = [(shoulder_x1, shoulder_y1), (shoulder_x2, shoulder_y2)]

        result = await run_in_threadpool(
            engine.process, 
            shirt_bytes, a4_bytes, 
            shirt_rect, a4_rect, 
            orig_w, orig_h,
            category_type,
            shoulder_pts
        )
        return result
    except ValueError as e:
        raise HTTPException(status_code=422, detail=str(e))
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"분석 중 오류 발생: {str(e)}")


